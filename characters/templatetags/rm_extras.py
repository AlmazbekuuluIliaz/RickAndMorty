"""Свои шаблонные фильтры проекта.

Здесь только перевод меток статуса и вида на русский. Сами имена персонажей
не трогаем — это данные из англоязычного API (см. решение по ТЗ).
Оригинальные значения в базе остаются английскими, переводим лишь при
отображении, поэтому повторный импорт fetch_rick_and_morty ничего не ломает.
"""

from django import template

register = template.Library()

# Перевод статуса. Ключи — ровно те строки, что приходят из API.
STATUS_RU = {
    'Alive': 'Жив',
    'Dead': 'Мёртв',
    'unknown': 'Неизвестно',
}

# Перевод вида. Покрывает все значения, что реально есть в базе; для любого
# нового/неизвестного вида фильтр вернёт оригинал (см. .get ниже).
SPECIES_RU = {
    'Human': 'Человек',
    'Alien': 'Пришелец',
    'Humanoid': 'Гуманоид',
    'Animal': 'Животное',
    'Robot': 'Робот',
    'Mythological Creature': 'Мифическое существо',
    'Poopybutthole': 'Пупибатхол',
    'Cronenberg': 'Кроненберг',
    'Disease': 'Болезнь',
    'unknown': 'Неизвестно',
}


@register.filter
def status_ru(value):
    """'Alive' -> 'Жив'. Пустую строку показываем как 'Неизвестно'."""
    return STATUS_RU.get(value, value or 'Неизвестно')


@register.filter
def species_ru(value):
    """'Human' -> 'Человек'. Незнакомый вид возвращаем как есть."""
    return SPECIES_RU.get(value, value)
